import os
import numpy as np
import libero
from libero.libero import benchmark
from libero.libero.envs import OffScreenRenderEnv

libero_path = os.path.dirname(libero.__file__)
b = benchmark.get_benchmark("libero_spatial")()
task = b.get_task(0)
bddl_file = os.path.join(libero_path, "libero", "bddl_files", task.problem_folder, task.bddl_file)
env = OffScreenRenderEnv(bddl_file_name=bddl_file, camera_widths=128, camera_heights=128, render_gpu_device_id=-1)
obs = env.reset()

print("Controller type:", env.env.robots[0].controller.name)
print("Controller default kp:", getattr(env.env.robots[0].controller, "kp", None))
print("Controller input type:", getattr(env.env.robots[0].controller, "input_type", None))

env.close()
