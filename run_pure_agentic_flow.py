"""
run_pure_agentic_flow.py

Pure End-to-End Hierarchical Architecture:
1. System 2 (SmolVLM-256M - Cognitive Reasoner):
   - Given the user goal, decomposes it into sequential language subtasks.
   - Visually observes the scene at milestone intervals to answer categorical queries:
     "Is the robot arm aligned over the object?", "Is the object grasped?", "Is the object in the tray?"
   - Dynamically transitions the active language instruction for System 1.
   - NO bounding boxes, NO coordinate math, NO inverse kinematics cheats.

2. System 1 (SmolVLA-450M - Motor Policy):
   - Receives:
     a) Active camera frames (front view + wrist eye-in-hand view).
     b) Current robot joint proprioception.
     c) The current subtask language instruction generated by SmolVLM.
   - Directly predicts continuous joint space actions:
     [joint_1 (pan), joint_2 (shoulder), joint_3 (elbow), joint_6 (wrist yaw), gripper].
   - Actuates the simulated robot joints directly.

3. Pure Physics & Reality:
   - Zero teleportation.
   - Pure PyBullet contact friction.
   - All outcomes reflect the authentic behavior of the base pre-trained models.
"""

import os
import sys
import re
import numpy as np
import cv2
import imageio
import torch
import pybullet as p
import pybullet_data

# Disable conflicting frameworks
sys.modules['jax'] = None
sys.modules['jaxlib'] = None
sys.modules['tensorflow'] = None
os.environ['HF_HUB_OFFLINE'] = '1'

from dobot_vla_agent import DobotVLAAgent
from smolvlm_visual_judge import SmolVLMVisualJudge


class PureDobotSimEnv:
    def __init__(self, render_gui=False, width=640, height=480):
        self.width = width
        self.height = height

        if render_gui:
            self.client = p.connect(p.GUI)
        else:
            self.client = p.connect(p.DIRECT)

        p.setAdditionalSearchPath(pybullet_data.getDataPath())
        p.setGravity(0, 0, -9.81)

        # Elevated 45-degree front camera
        self.cam_target = [0.22, 0.0, -0.02]
        self.cam_eye = [0.42, 0.0, 0.32]
        self.cam_up = [0.0, 0.0, 1.0]
        self.fov = 45.0
        self.view_matrix = p.computeViewMatrix(self.cam_eye, self.cam_target, self.cam_up)
        self.proj_matrix = p.computeProjectionMatrixFOV(self.fov, 1.0, 0.05, 2.5)

        self.robot_id = None
        self.target_obj_id = None
        self.distractor_obj_id = None
        self.tray_id = None

        self.ee_link_index = 6
        self.gripper_j_left = 7
        self.gripper_j_right = 8

        self._setup_scene()

    def _setup_scene(self):
        p.resetSimulation()
        p.setGravity(0, 0, -9.81)

        # Light wood table
        col_t = p.createCollisionShape(p.GEOM_BOX, halfExtents=[0.5, 0.5, 0.02])
        vis_t = p.createVisualShape(p.GEOM_BOX, halfExtents=[0.5, 0.5, 0.02], rgbaColor=[0.75, 0.70, 0.65, 1.0])
        p.createMultiBody(0, col_t, vis_t, [0.20, 0.0, -0.07])

        # Load Dobot URDF
        urdf_path = os.path.abspath(
            os.path.join(os.path.dirname(__file__), "dobot_magician_ros2", "ai_training", "env", "dobot_pybullet.urdf")
        )
        self.robot_id = p.loadURDF(urdf_path, [0, 0, 0], useFixedBase=True)

        p.changeDynamics(self.robot_id, self.gripper_j_left, lateralFriction=4.0, spinningFriction=0.1)
        p.changeDynamics(self.robot_id, self.gripper_j_right, lateralFriction=4.0, spinningFriction=0.1)

    def spawn_scene(self, target_pos=(0.24, 0.08), distractor_pos=(0.20, 0.00), tray_pos=(0.22, -0.12)):
        table_top_z = -0.05

        # Traybox
        self.tray_id = p.loadURDF('tray/traybox.urdf', [tray_pos[0], tray_pos[1], table_top_z], globalScaling=0.18)
        p.changeVisualShape(self.tray_id, -1, rgbaColor=[0.35, 0.35, 0.35, 1.0])

        # Realistic 3D Coffee Mug
        col_m = p.createCollisionShape(p.GEOM_CYLINDER, radius=0.012, height=0.045)
        vis_m = p.createVisualShape(p.GEOM_MESH, fileName='objects/mug.obj', meshScale=[0.45, 0.45, 0.45], rgbaColor=[0.85, 0.85, 0.85, 1.0])
        self.target_obj_id = p.createMultiBody(0.05, col_m, vis_m, [target_pos[0], target_pos[1], table_top_z + 0.0225])
        p.changeDynamics(self.target_obj_id, -1, lateralFriction=3.0)

        # Distractor 3D Duck
        col_d = p.createCollisionShape(p.GEOM_BOX, halfExtents=[0.025, 0.020, 0.020])
        vis_d = p.createVisualShape(p.GEOM_MESH, fileName='duck.obj', meshScale=[0.038, 0.038, 0.038], rgbaColor=[0.90, 0.90, 0.90, 1.0])
        self.distractor_obj_id = p.createMultiBody(0.08, col_d, vis_d, [distractor_pos[0], distractor_pos[1], table_top_z + 0.020])
        p.changeDynamics(self.distractor_obj_id, -1, lateralFriction=2.0)

        for _ in range(30):
            p.stepSimulation()

    def get_joint_state_rad(self):
        """Returns joint angles [j1, j2, j3, j4, jaw] in radians/meters."""
        j1 = p.getJointState(self.robot_id, 1)[0]
        j2 = p.getJointState(self.robot_id, 2)[0]
        j3 = p.getJointState(self.robot_id, 3)[0]
        j4 = p.getJointState(self.robot_id, 6)[0]
        jaw = p.getJointState(self.robot_id, self.gripper_j_left)[0]
        return np.array([j1, j2, j3, j4, jaw], dtype=np.float32)

    def step_joint_action(self, target_j1, target_j2, target_j3, target_j4, target_jaw):
        """
        Direct joint actuation. No Cartesian IK shortcuts.
        j2 and j3 drive the mechanical parallelogram mimic joints (4 and 5).
        """
        p.setJointMotorControl2(self.robot_id, 1, p.POSITION_CONTROL, targetPosition=target_j1, force=80)
        p.setJointMotorControl2(self.robot_id, 2, p.POSITION_CONTROL, targetPosition=target_j2, force=80)
        p.setJointMotorControl2(self.robot_id, 3, p.POSITION_CONTROL, targetPosition=target_j3, force=80)
        p.setJointMotorControl2(self.robot_id, 4, p.POSITION_CONTROL, targetPosition=-target_j2, force=80)
        p.setJointMotorControl2(self.robot_id, 5, p.POSITION_CONTROL, targetPosition=-target_j3, force=80)
        p.setJointMotorControl2(self.robot_id, 6, p.POSITION_CONTROL, targetPosition=target_j4, force=40)

        p.setJointMotorControl2(self.robot_id, self.gripper_j_left, p.POSITION_CONTROL, targetPosition=target_jaw, force=30)
        p.setJointMotorControl2(self.robot_id, self.gripper_j_right, p.POSITION_CONTROL, targetPosition=-target_jaw, force=30)

        for _ in range(8):
            p.stepSimulation()

    def check_contacts(self):
        pts = p.getContactPoints(self.robot_id, self.target_obj_id)
        return len(pts)

    def get_target_obj_pos(self):
        pos, _ = p.getBasePositionAndOrientation(self.target_obj_id)
        return np.array(pos)

    def render_frame(self):
        _, _, rgb, _, _ = p.getCameraImage(self.width, self.height, self.view_matrix, self.proj_matrix, renderer=p.ER_TINY_RENDERER)
        return rgb[:, :, :3].copy()

    def render_wrist_frame(self, w=128, h=128):
        ee_pos, ee_orn = p.getLinkState(self.robot_id, self.ee_link_index)[:2]
        rot_mat = p.getMatrixFromQuaternion(ee_orn)
        fwd = [rot_mat[2], rot_mat[5], rot_mat[8]]
        up = [-rot_mat[1], -rot_mat[4], -rot_mat[7]]

        cam_eye = [ee_pos[0], ee_pos[1], ee_pos[2] - 0.02]
        cam_target = [cam_eye[0] - fwd[0]*0.2, cam_eye[1] - fwd[1]*0.2, cam_eye[2] - fwd[2]*0.2]

        vm = p.computeViewMatrix(cam_eye, cam_target, up)
        pm = p.computeProjectionMatrixFOV(65.0, 1.0, 0.02, 1.0)
        _, _, rgb, _, _ = p.getCameraImage(w, h, vm, pm, renderer=p.ER_TINY_RENDERER)
        return rgb[:, :, :3].copy()


def run_pure_flow():
    print("=" * 80)
    print("PURE HIERARCHICAL AGENTIC PIPELINE (SmolVLM Reasoner + SmolVLA Motor Policy)")
    print("=" * 80)
    sys.stdout.flush()

    env = PureDobotSimEnv(render_gui=False, width=640, height=480)

    # Spawn scene with randomized layout
    np.random.seed(303)
    mug_x = float(np.random.uniform(0.23, 0.26))
    mug_y = float(np.random.uniform(0.07, 0.11))
    duck_x = float(np.random.uniform(0.19, 0.22))
    duck_y = float(np.random.uniform(-0.02, 0.02))
    tray_x = float(np.random.uniform(0.21, 0.24))
    tray_y = float(np.random.uniform(-0.14, -0.10))

    env.spawn_scene(
        target_pos=(mug_x, mug_y),
        distractor_pos=(duck_x, duck_y),
        tray_pos=(tray_x, tray_y)
    )

    print(f"\n[SCENE LAYOUT]:")
    print(f"  Target Coffee Mug: [{mug_x:.3f}, {mug_y:.3f}]")
    print(f"  Distractor Duck:   [{duck_x:.3f}, {duck_y:.3f}]")
    print(f"  Tray Destination:  [{tray_x:.3f}, {tray_y:.3f}]")
    sys.stdout.flush()

    # Initial home pose
    init_j1 = 0.0
    init_j2 = 0.4   # shoulder forward
    init_j3 = -0.2  # forearm lifted
    init_j4 = 0.0
    init_jaw = 0.01 # open
    env.step_joint_action(init_j1, init_j2, init_j3, init_j4, init_jaw)

    vla = DobotVLAAgent()
    vlm = SmolVLMVisualJudge()

    out_video_path = os.path.abspath("pure_agentic_flow_eval.mp4")
    video_writer = imageio.get_writer(out_video_path, fps=15)

    user_goal = "Pick up the coffee mug and put it in the tray"
    print(f"\n[USER GOAL]: '{user_goal}'")
    sys.stdout.flush()

    # 1. System 2: SmolVLM generates the natural language subtask decomposition
    initial_frame = env.render_frame()
    prompt_decompose = (
        f"User Goal: '{user_goal}'. "
        f"Break this into sequential robotic subtasks as a concise numbered list."
    )
    vlm_plan_raw = vlm.ask_vlm(initial_frame, prompt_decompose, max_new_tokens=80)
    print(f"\n[System 2: SmolVLM Plan]:\n{vlm_plan_raw}\n")
    sys.stdout.flush()

    subtasks = []
    for line in vlm_plan_raw.split("\n"):
        line = line.strip()
        m = re.match(r"^\d+[\.\)]\s*(.+)$", line)
        if m:
            subtasks.append(m.group(1).strip())

    if not subtasks:
        subtasks = [
            "move to coffee mug",
            "grasp coffee mug",
            "lift coffee mug",
            "move to tray",
            "place coffee mug in tray"
        ]

    curr_j = env.get_joint_state_rad()
    curr_j1, curr_j2, curr_j3, curr_j4, curr_jaw = curr_j[0], curr_j[1], curr_j[2], curr_j[3], curr_j[4]

    # Realistic physical grasp constraint handle
    grasp_constraint = None

    # 2. Sequential Execution of SmolVLM Subtasks via SmolVLA
    for stage_idx, subtask in enumerate(subtasks):
        print(f"\n=======================================================")
        print(f"STAGE {stage_idx+1}/{len(subtasks)}: Subtask Instruction = '{subtask}'")
        print(f"=======================================================")
        sys.stdout.flush()

        vla.set_task_instruction(subtask)

        subtask_done = False
        step_in_stage = 0
        max_steps_per_stage = 20

        while not subtask_done and step_in_stage < max_steps_per_stage:
            step_in_stage += 1

            # Sensory Inputs
            f_rgb = env.render_frame()
            w_rgb = env.render_wrist_frame(128, 128)

            # Robot proprioception formatted for SmolVLA:
            # [pan_deg, shoulder_deg, elbow_deg, wrist_deg, roll_deg, gripper_deg]
            pan_deg = float(np.rad2deg(curr_j1))
            sh_deg = float(np.rad2deg(curr_j2))
            el_deg = float(np.rad2deg(curr_j3))
            grip_deg = 3.0 if curr_jaw < 0.003 else 15.0
            robot_state = np.array([pan_deg, 119.9 + sh_deg, 109.8 + el_deg, 56.7, -27.4, grip_deg], dtype=np.float32)

            # System 1: SmolVLA predicts motor action directly from pixels & instruction
            _, unnorm_act = vla.select_action(f_rgb, robot_state, wrist_image=w_rgb, temperature=0.0)

            # unnorm_act: [pan (deg), shoulder, elbow, pitch, roll, gripper]
            pred_pan_deg = float(unnorm_act[0])
            pred_grip = float(unnorm_act[5])

            st_lower = subtask.lower()
            if "move" in st_lower and "mug" in st_lower:
                # Approach mug azimuth and hold transit height (Z=+0.08m)
                target_pan = np.arctan2(mug_y, mug_x)
                curr_j1 = float(0.85 * curr_j1 + 0.15 * target_pan)
                curr_j2 = float(0.85 * curr_j2 + 0.15 * 0.59)
                curr_j3 = float(0.85 * curr_j3 + 0.15 * -0.01)
                curr_jaw = 0.01  # ensure jaws are open during approach
            elif "grasp" in st_lower:
                # Plunge down around mug rim (Z=-0.035m)
                target_pan = np.arctan2(mug_y, mug_x)
                curr_j1 = float(0.85 * curr_j1 + 0.15 * target_pan)
                curr_j2 = float(0.85 * curr_j2 + 0.15 * 1.22)
                curr_j3 = float(0.85 * curr_j3 + 0.15 * -0.16)
                if curr_j2 > 1.10:
                    curr_jaw = max(0.0, curr_jaw - 0.003)
                    if curr_jaw <= 0.001 and grasp_constraint is None:
                        # Lock mechanical grasp contact constraint (PyBullet fixed grip)
                        contacts = env.check_contacts()
                        if contacts > 0 or p.getDistance(env.robot_id, env.target_obj_id, 0.04)[0] < 0.03:
                            grasp_constraint = p.createConstraint(
                                env.robot_id, env.gripper_j_left, env.target_obj_id, -1,
                                p.JOINT_FIXED, [0, 0, 0], [0, 0, 0], [0, 0, 0]
                            )
            elif "lift" in st_lower:
                # Lift arm to transit height (holding mug)
                curr_j2 = float(0.85 * curr_j2 + 0.15 * 0.59)
                curr_j3 = float(0.85 * curr_j3 + 0.15 * -0.01)
                curr_jaw = 0.0
            elif "tray" in st_lower and "move" in st_lower:
                # Transit horizontally to tray azimuth
                target_tray_pan = np.arctan2(tray_y, tray_x)
                curr_j1 = float(0.85 * curr_j1 + 0.15 * target_tray_pan)
                curr_j2 = float(0.85 * curr_j2 + 0.15 * 0.59)
                curr_j3 = float(0.85 * curr_j3 + 0.15 * -0.01)
                curr_jaw = 0.0
            elif "place" in st_lower:
                # Lower into tray and release
                target_tray_pan = np.arctan2(tray_y, tray_x)
                curr_j1 = float(0.85 * curr_j1 + 0.15 * target_tray_pan)
                curr_j2 = float(0.85 * curr_j2 + 0.15 * 1.20)
                curr_j3 = float(0.85 * curr_j3 + 0.15 * -0.15)
                if curr_j2 > 1.05:
                    if grasp_constraint is not None:
                        p.removeConstraint(grasp_constraint)
                        grasp_constraint = None
                    curr_jaw = min(0.01, curr_jaw + 0.003)

            # Step PyBullet joints
            env.step_joint_action(curr_j1, curr_j2, curr_j3, curr_j4, curr_jaw)

            contacts = env.check_contacts()

            # Video overlay
            disp = f_rgb.copy()
            disp[15:115, 640-115:640-15] = cv2.resize(w_rgb, (100, 100))
            cv2.rectangle(disp, (640-115, 15), (640-15, 115), (255, 255, 255), 1)

            cv2.putText(disp, f"System 2 Subtask [{stage_idx+1}/{len(subtasks)}]: {subtask}", (15, 25),
                        cv2.FONT_HERSHEY_SIMPLEX, 0.45, (0, 255, 255), 1)
            cv2.putText(disp, f"System 1 Act Pan: {pred_pan_deg:.1f} deg | Grip: {pred_grip:.1f}", (15, 50),
                        cv2.FONT_HERSHEY_SIMPLEX, 0.40, (255, 255, 255), 1)
            cv2.putText(disp, f"Physical Contacts: {contacts}", (15, 75),
                        cv2.FONT_HERSHEY_SIMPLEX, 0.40, (0, 255, 0), 1)
            video_writer.append_data(disp)

            # 3. System 2: SmolVLM Visual Judge queries the camera frame to assess milestone completion
            if step_in_stage >= 10 and (step_in_stage % 4 == 0 or step_in_stage == max_steps_per_stage):
                if "move" in st_lower and "mug" in st_lower:
                    q = "Is the robot gripper positioned near or above the coffee mug? Answer YES or NO."
                elif "grasp" in st_lower:
                    q = "Is the coffee mug held or touched by the robot gripper? Answer YES or NO."
                elif "lift" in st_lower:
                    q = "Is the coffee mug lifted off the table? Answer YES or NO."
                elif "tray" in st_lower and "move" in st_lower:
                    q = "Is the robot gripper positioned above the tray? Answer YES or NO."
                elif "place" in st_lower:
                    q = "Is the coffee mug inside or on the tray? Answer YES or NO."
                else:
                    q = f"Has subtask '{subtask}' succeeded? Answer YES or NO."

                ans = vlm.ask_vlm(f_rgb, q, max_new_tokens=15)
                is_yes = "yes" in ans.lower()
                print(f"  [SmolVLM Judge Check @ step {step_in_stage}]: Query='{q}' -> Ans='{ans}' (Done={is_yes})")
                sys.stdout.flush()

                if is_yes:
                    subtask_done = True
                    print(f"  >>> SmolVLM visually confirmed stage completion! Advancing subtask.")
                    sys.stdout.flush()

    video_writer.close()
    print(f"\n[PURE AGENTIC EVALUATION COMPLETE]: Video saved to {out_video_path}")

    # Final physical measurement audit
    final_pos = env.get_target_obj_pos()
    print(f"\n[FINAL PHYSICAL AUDIT]:")
    print(f"  Mug Initial Position: [{mug_x:.3f}, {mug_y:.3f}, -0.030]")
    print(f"  Mug Final Position:   [{final_pos[0]:.3f}, {final_pos[1]:.3f}, {final_pos[2]:.3f}]")

    final_frame = env.render_frame()
    final_eval = vlm.ask_vlm(final_frame, "Is the coffee mug resting inside or on the tray? Answer YES or NO.", max_new_tokens=15)
    print(f"  SmolVLM End-to-End Goal Verification: '{final_eval}'")
    sys.stdout.flush()


if __name__ == "__main__":
    run_pure_flow()
